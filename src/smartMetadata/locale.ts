import type { SmartMetadataLocale } from './types';

const LOCALE_STORAGE_KEY = 'as_app_locale';

export const SMART_METADATA_LOCALES: SmartMetadataLocale[] = [
  'en',
  'ja',
  'ru',
  'es',
  'fr',
  'de',
  'pt',
];


/** Human-readable preset labels (English keys → localized where useful). */
export function labelPreset(
  locale: SmartMetadataLocale,
  category: string,
  value: string
): string {
  const key = `${category}:${value}`;
  const table: Record<string, Partial<Record<SmartMetadataLocale, string>>> = {
    'scene:studio': { ja: 'スタジオ', ru: 'Студия', es: 'Estudio' },
    'scene:sunset': { ja: '夕焼け', ru: 'Закат', es: 'Atardecer' },
    'scene:nightclub': { ja: 'ナイトクラブ', ru: 'Клуб' },
    'scene:cyber': { ja: 'サイバー', ru: 'Кибер' },
    'light:neon': { ja: 'ネオン', ru: 'Неон' },
    'light:concert': { ja: 'コンサート', ru: 'Концерт' },
    'weather:rain': { ja: '雨', ru: 'Дождь', es: 'Lluvia' },
    'weather:snow': { ja: '雪', ru: 'Снег', es: 'Nieve' },
    'weather:fog': { ja: '霧', ru: 'Туман', es: 'Niebla' },
    'time:night': { ja: '夜', ru: 'Ночь', es: 'Noche' },
    'time:golden_hour': { ja: 'ゴールデンアワー', ru: 'Золотой час' },
    'time:day': { ja: '昼', ru: 'День', es: 'Día' },
  };
  const row = table[key];
  if (row?.[locale]) return row[locale]!;
  return value.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
}
